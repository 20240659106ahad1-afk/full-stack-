CREATE TABLE IF NOT EXISTS route_distances (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  start_district_id BIGINT NOT NULL REFERENCES districts(id),
  package_id BIGINT NOT NULL REFERENCES packages(id) ON DELETE CASCADE,
  distance_km DOUBLE PRECISION NOT NULL CHECK (distance_km > 0),
  UNIQUE (start_district_id, package_id)
);

CREATE TABLE IF NOT EXISTS snack_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  price DOUBLE PRECISION NOT NULL CHECK (price >= 0),
  image_url TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS booking_seats (
  booking_id BIGINT NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  seat_number BIGINT NOT NULL CHECK (seat_number > 0),
  PRIMARY KEY (booking_id, seat_number)
);

CREATE TABLE IF NOT EXISTS restaurants (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  package_stop_id BIGINT NOT NULL REFERENCES package_stops(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  UNIQUE (package_stop_id, name)
);

CREATE TABLE IF NOT EXISTS restaurant_menu_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
  meal_type TEXT NOT NULL CHECK (meal_type IN ('breakfast','lunch','dinner','snacks')),
  name TEXT NOT NULL,
  price DOUBLE PRECISION NOT NULL CHECK (price >= 0),
  image_url TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS booking_food_orders (
  booking_id BIGINT NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  day BIGINT NOT NULL CHECK (day BETWEEN 1 AND 7),
  meal_type TEXT NOT NULL CHECK (meal_type IN ('breakfast','lunch','dinner','snacks')),
  person_number BIGINT NOT NULL CHECK (person_number > 0),
  restaurant_id BIGINT NOT NULL REFERENCES restaurants(id),
  menu_item_id BIGINT NOT NULL REFERENCES restaurant_menu_items(id),
  quantity BIGINT NOT NULL DEFAULT 1 CHECK (quantity BETWEEN 1 AND 10),
  PRIMARY KEY (booking_id, day, meal_type, person_number)
);

CREATE TABLE IF NOT EXISTS user_food_preferences (
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  meal_type TEXT NOT NULL CHECK (meal_type IN ('breakfast','lunch','dinner','snacks')),
  dish_name TEXT NOT NULL,
  PRIMARY KEY (user_id, meal_type)
);

CREATE TABLE IF NOT EXISTS schema_migrations (
  name TEXT PRIMARY KEY,
  applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS meal_packages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  description TEXT NOT NULL,
  breakfast_id BIGINT NOT NULL REFERENCES meal_items(id),
  lunch_id BIGINT NOT NULL REFERENCES meal_items(id),
  dinner_id BIGINT NOT NULL REFERENCES meal_items(id)
);

CREATE TABLE IF NOT EXISTS booking_meal_days (
  booking_id BIGINT NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  day BIGINT NOT NULL CHECK (day BETWEEN 1 AND 7),
  package_id BIGINT NOT NULL REFERENCES meal_packages(id),
  PRIMARY KEY (booking_id, day)
);

CREATE TABLE IF NOT EXISTS otps (
  key TEXT PRIMARY KEY,
  code_hash TEXT NOT NULL,
  expires_at BIGINT NOT NULL,
  attempts BIGINT NOT NULL DEFAULT 0,
  created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS feedback (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id),
  booking_id BIGINT REFERENCES bookings(id) ON DELETE SET NULL,
  rating BIGINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
  comment TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

